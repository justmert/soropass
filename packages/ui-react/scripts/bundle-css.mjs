/**
 * Emit a self-contained `styles.css` inside this package by concatenating the
 * token surface + component styles from @soropass/ui. The design-sync converter
 * bounds `cssEntry` to the package dir, so the real stylesheet (which lives in
 * the sibling @soropass/ui) has to be materialized locally. Regenerated on every
 * build; the file is gitignored.
 */
/* global process */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const styledDir = resolve(here, '../../ui/styled');

const tokens = readFileSync(resolve(styledDir, 'tokens.css'), 'utf8');
const passkey = readFileSync(resolve(styledDir, 'passkey.css'), 'utf8');

const banner =
  '/* GENERATED by @soropass/ui-react build (bundle-css.mjs) — do not edit.\n' +
  '   Source: @soropass/ui styled/tokens.css + styled/passkey.css. */\n';

writeFileSync(resolve(here, '../styles.css'), `${banner}\n${tokens}\n${passkey}\n`);
process.stderr.write('bundle-css: wrote styles.css\n');
